const assert = require("node:assert/strict");
const test = require("node:test");
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const root = path.resolve(__dirname, "../..");

function javascriptWidgetArgumentCounts() {
  const sourceText = fs.readFileSync(path.join(root, "App.tsx"), "utf8");
  const source = ts.createSourceFile("App.tsx", sourceText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const counts = [];
  const visit = (node) => {
    if (ts.isCallExpression(node)
      && ts.isPropertyAccessExpression(node.expression)
      && node.expression.name.text === "updateSleepWindow") {
      counts.push(node.arguments.length);
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return counts;
}

function nativeWidgetArgumentCount(sourceText, label) {
  const match = sourceText.match(/fun updateSleepWindow\(([^)]*)\)/);
  assert.ok(match, `${label} must declare updateSleepWindow`);
  return match[1].split(",").map((part) => part.trim()).filter((part) => !/\bPromise\b/.test(part)).length;
}

test("Android widget JS call matches both native module signatures", () => {
  const javascriptCounts = javascriptWidgetArgumentCounts();
  assert.equal(javascriptCounts.length, 1, "the widget update should have one call site");

  const modulePath = path.join(root, "android/app/src/main/java/com/uykuva/app/UykuvaWidgetModule.kt");
  const moduleCount = nativeWidgetArgumentCount(fs.readFileSync(modulePath, "utf8"), "Android module");
  const pluginPath = path.join(root, "plugins/withUykuvaWidget.js");
  const pluginCount = nativeWidgetArgumentCount(fs.readFileSync(pluginPath, "utf8"), "Expo config plugin");

  assert.equal(javascriptCounts[0], moduleCount, "App.tsx call must match the compiled Kotlin module");
  assert.equal(javascriptCounts[0], pluginCount, "App.tsx call must match the module generated by prebuild");
});
